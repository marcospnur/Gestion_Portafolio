def aduana_etfs_v46():
    print(f"\n{'='*85}")
    print(f" 🛡️ ADUANA DE ETFs V2.0 - COHESIÓN Y EFICIENCIA")
    print(f"{'='*85}")

    # --- CONTEXTO GLOBAL ---
    mis_acciones = Activos_historicos
    mis_etfs_existentes = ETFs_historicos

    etf_input = input("ETF a evaluar: ").upper()
    benchmark = "VOO"
    end = datetime.date.today()
    start_5y = end - datetime.timedelta(days=5*365 + 10)

    try:
        t = yf.Ticker(etf_input)
        info = t.info

        # --- DATOS FUNDAMENTALES ---
        exp_ratio = info.get('expenseRatio')
        if exp_ratio is None:
            print(f"⚠️ No se detectó costo anual para {etf_input} automáticamente.")
            exp_ratio = float(input(f"   Por favor, ingresa el costo de la App (ej. 0.05): ")) / 100

        div_yield = info.get('trailingAnnualDividendYield') or info.get('yield') or 0
        aum = (info.get('totalAssets') or info.get('marketCap') or 0) / 1e9

        # Universo completo para matriz de correlación
        all_tickers = list(set([etf_input, benchmark] + mis_acciones + mis_etfs_existentes))
        data_raw = yf.download(all_tickers, start=start_5y, end=end, progress=False, auto_adjust=True)['Close'].ffill()

    except Exception as e:
        print(f"❌ Error crítico: {e}")
        return

    # --- MÉTRICAS DE INGENIERÍA (Duelo de Sharpe) ---
    def calcular_metricas(ticker):
        df = data_raw[ticker].tail(252).dropna() # Ventana de 1 año para decisión mensual
        ret = (df.iloc[-1] / df.iloc[0]) - 1
        vol = np.log(df / df.shift(1)).std() * np.sqrt(252)
        sharpe = (ret - 0.035) / vol if vol > 0 else 0
        mdd = ((df - df.cummax()) / df.cummax()).min()
        return ret, vol, sharpe, mdd

    ret_in, vol_in, sharpe_in, mdd_in = calcular_metricas(etf_input)

    # --- CÁLCULO DE CORRELACIONES (1 AÑO) ---
    returns_1y = np.log(data_raw.tail(252) / data_raw.tail(252).shift(1)).dropna()

    # 1. vs Acciones (70%)
    corr_acc_avg = np.mean([returns_1y[etf_input].corr(returns_1y[acc]) for acc in mis_acciones])

    # 2. vs Otros ETFs (30%) - Duelo de Eficiencia
    max_corr_etf = 0
    rival_nombre = "N/A"
    es_sustituto = False
    duelo_msg = ""

    otros_etfs = [e for e in mis_etfs_existentes if e != etf_input]
    if otros_etfs:
        corrs = {e: returns_1y[etf_input].corr(returns_1y[e]) for e in otros_etfs}
        rival_nombre = max(corrs, key=corrs.get)
        max_corr_etf = corrs[rival_nombre]

        if max_corr_etf > 0.80: # Umbral de redundancia técnica
            _, _, sharpe_rival, _ = calcular_metricas(rival_nombre)
            if sharpe_in > (sharpe_rival * 1.05): # Margen del 5% para justificar el cambio
                es_sustituto = True
                duelo_msg = f"🚀 SUPERIOR: {etf_input} ({sharpe_in:.2f}) vs {rival_nombre} ({sharpe_rival:.2f})"
            else:
                duelo_msg = f"📉 INFERIOR: {etf_input} ({sharpe_in:.2f}) vs {rival_nombre} ({sharpe_rival:.2f})"

    # --- PANTALLA DE RESULTADOS ---
    print(f"\n📊 FUNDAMENTALES:")
    print(f"- Patrimonio (AUM): ${aum:.2f}B {'✅' if aum > 1 else '❌'}")
    print(f"- Gasto Anual: {exp_ratio*100:.3f}% {'✅' if exp_ratio < 0.0035 else '⚠️'}")

    print(f"\n🔗 COHESIÓN Y CORRELACIÓN:")
    print(f"- Corr. Avg vs Acciones: {corr_acc_avg:.2f} {'⚠️ ESPEJO' if corr_acc_avg > 0.75 else '✅ ORTOGONAL'}")
    if otros_etfs:
        print(f"- Rival más parecido: {rival_nombre} (Corr: {max_corr_etf:.2f})")
        if max_corr_etf > 0.80:
            print(f"⚔️ DUELO DE EFICIENCIA: {duelo_msg}")

    # --- VEREDICTO DE INGENIERÍA ---
    f1_aum = aum > 1.0
    f2_costo = exp_ratio < 0.0035
    f3_vol = vol_in < 0.35 # Volatilidad menor al 35% para el bloque de seguridad
    f4_orto = corr_acc_avg < 0.75
    f5_duelo = not (max_corr_etf > 0.80 and not es_sustituto)

    print(f"\n{'='*85}")
    print(f"1. Liquidez: {'✅' if f1_aum else '❌'} | 2. Costo: {'✅' if f2_costo else '❌'} | 3. Sigma < 35%: {'✅' if f3_vol else '❌'}")
    print(f"4. Ortogonalidad: {'✅' if f4_orto else '⚠️'} | 5. Eficiencia Relativa: {'✅' if f5_duelo else '❌'}")

    if all([f1_aum, f2_costo, f3_vol, f5_duelo]):
        if es_sustituto:
            print(f"\nVEREDICTO: 🔄 REEMPLAZO SUGERIDO. Saca {rival_nombre} y mete {etf_input}.")
        elif max_corr_etf > 0.80:
            print(f"\nVEREDICTO: ❌ RECHAZADO POR REDUNDANCIA INEFICIENTE.")
        else:
            print(f"\nVEREDICTO: ✅ {etf_input} ES APTO (NUEVA DIVERSIFICACIÓN).")
    else:
        print(f"\nVEREDICTO: ❌ {etf_input} RECHAZADO.")
        if not f5_duelo: print(f"   -> MOTIVO: Es redundante con {rival_nombre} y tiene menor Sharpe Ratio.")

aduana_etfs_v46()