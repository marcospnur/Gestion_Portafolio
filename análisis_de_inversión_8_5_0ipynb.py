def sortino_objective(w, R_matrix):
    port_ret = R_matrix.dot(w)
    dd = np.sqrt(np.mean(np.minimum(0, port_ret - (0.045/252))**2)) * np.sqrt(252)
    ret_anual = np.exp(port_ret.mean() * 252) - 1
    return (ret_anual - 0.045) / dd if dd > 0 else -100

def check_constraints_v852(w, posiciones, cap_mcmc, acciones, etfs, todos, residuos_dic):
    # Validar normalización absoluta
    if abs(np.sum(w) - 1.0) > 1e-4:
        return False

    # 1. Filtro estricto de pesos activos y cardinalidad mínima
    activos_en_cartera = np.sum(w > 0.005)
    if activos_en_cartera < 6:
        return False

    for i, peso in enumerate(w):
        if peso > 0.005 and (peso < 0.03 or peso > 0.20):
            return False

    # 2. Mix de Silos
    peso_acc = np.sum([w[todos.index(a)] for a in acciones])
    peso_etf = np.sum([w[todos.index(a)] for a in etfs])
    if not (0.60 <= peso_acc <= 0.95) or not (0.05 <= peso_etf <= 0.40): # Changed 0.20 to 0.05 for peso_etf min
        return False

    # 3. Restricciones del Semáforo de 5 Zonas (Validación Vectorial)
    for i, a in enumerate(todos):
        p_rank = residuos_dic[a]
        peso_actual_nom = posiciones[a] / cap_mcmc

        # Z1, Z3, Z4: No pueden recibir capital nuevo (Techo duro)
        if p_rank > 95.0 or (1.0 < p_rank <= 60.0):
            if w[i] > peso_actual_nom + 0.001:
                return False

        # Z5: Liquidación Absoluta
        if p_rank <= 1.0 and w[i] > 0.005:
            return False

    return True

# --- GENERADOR DE SEMILLA HEURÍSTICO ---
# Construye un portafolio de origen matemáticamente inquebrantable
w_nom = np.array([posiciones[a] for a in todos]) / cap_mcmc

def generar_semilla_valida():
    for _ in range(100000):
        w = np.zeros(len(todos))

        # 1. Asignar capital a las zonas restringidas (Z1, Z3, Z4) sin superar el límite nominal
        for i, a in enumerate(todos):
            p_rank = residuos_dic[a]
            max_w = min(w_nom[i], 0.20)
            if p_rank > 95.0 or (1.0 < p_rank <= 60.0):
                if max_w >= 0.03:
                    # Mantenemos parcial o totalmente la posición para no romper inercia
                    w[i] = np.random.uniform(0.03, max_w)

        # 2. Asignar capital a la zona libre (Z2) para cumplir cardinalidad
        z2_idx = [i for i, a in enumerate(todos) if 60.0 < residuos_dic[a] <= 95.0]
        activos_actuales = np.sum(w > 0)
        faltantes = max(0, 6 - activos_actuales)

        if len(z2_idx) < faltantes:
            continue # Imposible cumplir cardinalidad con el mercado actual

        # Elegir cuántos activos de Z2 activar
        k_z2 = np.random.randint(faltantes, len(z2_idx) + 1) if len(z2_idx) > faltantes else faltantes
        if k_z2 > 0:
            elegidos_z2 = np.random.choice(z2_idx, k_z2, replace=False)
            for i in elegidos_z2:
                w[i] = 0.03 # Base mínima para evitar exclusión

        # 3. Empujar la suma al 100% financiando exclusivamente los activos Z2
        suma = np.sum(w)
        if suma > 1.0:
            continue # Nos excedimos con los mínimos

        falta = 1.0 - suma
        if k_z2 > 0 and falta > 0:
            dist = np.random.dirichlet(np.ones(k_z2)) * falta
            for j, idx in enumerate(elegidos_z2):
                w[idx] += dist[j]

        # Evaluamos pureza matemática de la semilla
        if check_constraints_v852(w, posiciones, cap_mcmc, acciones, etfs, todos, residuos_dic):
            return w

    return None

