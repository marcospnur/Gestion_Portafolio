print(" 3. RESUMEN POST-AJUSTE (PMPT)")
print("-" * 120)
print(f" Rendimiento Esperado:            {rp_post:.2%}")
print(f" Downside Dev (Riesgo a la Baja): {dd_post:.2%}")
print(f" Sortino Ratio Esperado:          {sr_post:.2f}")
print(f" Max Drawdown:                    {mdd_post:.2%}")
print(f" Índice de Bernstein (PMPT):      {bernstein:.4f}")
print(f" Correlación Media (Spearman):    {np.mean(corr_spearman):.4f}")
print("-" * 120)
