R_f = 0.045
periodos = [1, 2, 3, 5, 10]

def aduana_integral():
    activo_input = input("Activo a evaluar: ").upper()
    activos_actuales = Activos_historicos

    end = datetime.date.today()
    start_5y = end - datetime.timedelta(days=3*365 + 10)

    # 1. DESCARGA ÚNICA (Ajustada por dividendos/splits)
    todo = [activo_input] + activos_actuales
    try:
        data = yf.download(todo, start=start_5y, end=end, progress=False, auto_adjust=True)['Close']
    except:
        print("❌ Error en la descarga de datos.")
        return

    if data[activo_input].isnull().all():
        print(f"❌ Error: Ticker '{activo_input}' no encontrado o sin datos.")
        return

    # 2. CÁLCULO DE MÉTRICAS HISTÓRICAS
    resultados_finales = []
    for p in periodos:
        dias = p * 252
        df_p = data[activo_input].tail(dias).dropna()

        if len(df_p) < 100: continue

        rets_log = np.log(df_p / df_p.shift(1)).dropna()
        rend_anual = np.exp(rets_log.mean() * 252) - 1
        sigma_anual = rets_log.std() * np.sqrt(252)
        sr = (rend_anual - R_f) / sigma_anual

        # MDD sobre precios ajustados
        rolling_max = df_p.cummax()
        mdd = ((df_p - rolling_max) / rolling_max).min()

        resultados_finales.append({
            "Activo": activo_input,
            "Periodo": f"{p}A",
            "SR": sr,
            "Retorno %": rend_anual * 100,
            "Sigma %": sigma_anual * 100,
            "MDD %": mdd * 100
        })

    # 3. IMPRESIÓN DE PIZARRA DE VALIDACIÓN
    df_pizarra = pd.DataFrame(resultados_finales)
    print(f"\n{'='*75}")
    print(f" PIZARRA DE VALIDACIÓN HISTÓRICA: {activo_input}")
    print(f"{'='*75}")
    print(tabulate(df_pizarra, headers='keys', tablefmt='psql', floatfmt=".2f"))

    # 4. ANÁLISIS DE DIVERSIFICACIÓN
    print("\n--- ANÁLISIS DE DIVERSIFICACIÓN (Correlación 2Y) ---")
    data_2y = data.tail(3*252).pct_change().dropna()
    corr_series = data_2y.corr()[activo_input].loc[activos_actuales]

    df_corr = pd.DataFrame(corr_series)
    print(tabulate(df_corr, headers=['Ticker', activo_input], tablefmt='psql', floatfmt=".2f"))

    # Interpretación de Correlación
    promedio_corr = corr_series.mean()
    print(f"\nCorrelación Promedio: {promedio_corr:.2f}")

    if promedio_corr > 0.20:
        print("⚠️ ALERTA: Este activo es muy similar a tu cartera actual.")
    elif promedio_corr <= 0.20:
        print("✅ DIVERSIFICACIÓN: Este activo aporta movimientos distintos.")

    for ticker, corr_val in corr_series.items():
        if abs(corr_val) > 0.75:
            print(f"⚠️ ALERTA: Correlación muy fuerte ({corr_val:.2f}) con {ticker}.")
        elif abs(corr_val) < 0.20:
            print(f"✅ DIVERSIFICACIÓN: Correlación muy baja ({corr_val:.2f}) con {ticker}.")

    # 5. VEREDICTO FINAL CON DOBLE FILTRO
    print(f"\n{'='*75}")
    print(f" RESULTADO FINAL DEL ANÁLISIS")
    print(f"{'='*75}")

    # Filtro 1: Consistencia SR
    aprobados_sr = sum(1 for x in resultados_finales if x['SR'] > 1.0)
    # Filtro 2: Eficiencia de Riesgo (Retorno > |MDD| en el promedio de los periodos evaluados)
    # Exigimos que al menos en el corto (1A) y medio plazo (3A) el retorno supere al susto
    eficiencia_1a = resultados_finales[0]['Retorno %'] > abs(resultados_finales[0]['MDD %'])
    eficiencia_3a = any(x['Retorno %'] > abs(x['MDD %']) for x in resultados_finales if x['Periodo'] == '3A')

    print(f"1. Consistencia SR (>1.0): {aprobados_sr}/5 periodos.")
    print(f"2. Eficiencia 1A (Retorno > |MDD|): {'✅ PASA' if eficiencia_1a else '❌ FALLA'}")
    print(f"3. Eficiencia 3A (Retorno > |MDD|): {'✅ PASA' if eficiencia_3a else '❌ FALLA'}")

    if aprobados_sr >= 3 and eficiencia_1a and eficiencia_3a:
        print(f"\nVEREDICTO: ✅ {activo_input} ES APTO PARA EL MCMC")
    else:
        print(f"\nVEREDICTO: ❌ {activo_input} RECHAZADO")
        if aprobados_sr < 3:
            print("- Razón: No cumple la consistencia de Sharpe Ratio mínima.")
        if not (eficiencia_1a and eficiencia_3a):
            print("- Razón: Riesgo Asimétrico (La caída máxima supera al rendimiento esperado).")
    print(f"{'='*75}\n")

